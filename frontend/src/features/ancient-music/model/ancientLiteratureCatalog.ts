function add(workId: string, detail: LiteratureDetail): AncientLiteratureRecord {
  const entry = works.get(workId)
  if (!entry) throw new Error(`Unknown ancient work: ${workId}`)
  const { work, tradition } = entry
  return {
    workId,
    title: work.title,
    originalTitle: work.originalTitle,
    date: work.date,
    author: work.author,
    tradition: tradition.name,
    place: tradition.place,
    evidence: work.evidence,
    ...detail,
    sources: [
      {
        label: work.sourceTitle,
        reference: `Каталожная запись или научное издание памятника «${work.title}».`,
        url: work.sourceUrl,
        kind: 'Каталог памятника',
      },
      ...detail.sources,
    ],
  }
}


export interface LiteratureSource {
  label: string
  reference: string
  url: string
  kind: 'Текст и перевод' | 'Каталог памятника' | 'Исследование' | 'Цифровое издание'
}

export interface AncientLiteratureRecord {
  workId: string
  title: string
  originalTitle?: string
  date: string
  author: string
  tradition: string
  place: string
  evidence: AncientEvidence
  language: string
  genre: string
  relationship: string
  description: string
  survival: string
  manuscript: string
  history: string[]
  themes: string[]
  sources: LiteratureSource[]
}

type LiteratureDetail = Pick<AncientLiteratureRecord,
  'language' | 'genre' | 'relationship' | 'description' | 'survival' | 'manuscript' | 'history' | 'themes'
> & { sources: LiteratureSource[] }

